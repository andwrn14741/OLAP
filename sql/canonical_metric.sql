-- ============================================================
-- З04 / З11. Эталон главной метрики
-- Метрика: валовой оборот сети «АвтоДеталь»
-- Определение: SUM(fact_sales.total_amount)
-- Условие сверки с карточкой: продажи с 2025-01-01 по 2025-12-31
-- Возвратов в сырье нет, оборот валовой.
-- ============================================================

SELECT
    SUM(total_amount) AS revenue
FROM fact_sales
WHERE sale_date >= '2025-01-01'
  AND sale_date <= '2025-12-31';
