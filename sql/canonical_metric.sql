-- Метрика: валовой оборот сети «АвтоДеталь»
-- Определение: SUM(fact_sales.total_amount)
-- Возвратов в сырье нет, поэтому оборот валовой, не чистый.
-- Источник: passport.md, раздел 7
-- ============================================================

SELECT
    SUM(total_amount) AS revenue
FROM fact_sales;
